#!/usr/bin/env Rscript
# ─────────────────────────────────────────────────────────────────────────────
# run_jobs.R  —  Tier 4 serializer.
#
# Writes  data/btos-jobs-monitor-data.js  defining a global:
#   window.BTOS_JOBS_MONITOR = { ... }
# consumed by the Job Displacement tab (jobs_displacement.html, synced into
# index.html) via assets/jobs-charts.js: section 03 reads a1, section 04 reads
# a2. The monitor block is retained but nothing currently renders it — the old
# dashboard markup and assets/jobs-monitor-charts.js were dropped 2026-07-31.
#
# This is a SLICE of btos_jobs.json, not the whole thing. The upstream research
# repo shipped a four-tab dashboard off the full object (all 96 cross-section
# coefficients, the panel, the AV plot, the placebos). This site uses only the
# descriptive monitor, so we ship ~44 KB instead of ~255 KB and the regression
# machinery stays in btos/output/ for anyone who wants it. If you add an exhibit
# that needs another block, add its key to MONITOR_KEEP or TOP_KEEP below.
#
# Assumes btos/03_jobs_join.R has run. Does not touch the network.
#
# Usage:  Rscript data_analysis/btos/run_jobs.R
# ─────────────────────────────────────────────────────────────────────────────

suppressMessages(library(jsonlite))

.file    <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
repo     <- if (length(.file)) dirname(dirname(normalizePath(.file))) else normalizePath(getwd())
src      <- file.path(repo, "btos", "output", "btos_jobs.json")
# `repo` is data_analysis/ in this layout; index.html reads data/ at the site
# root, one level up. Keep these two in step if the tree ever moves.
data_dir <- file.path(dirname(repo), "data")
dir.create(data_dir, showWarnings = FALSE, recursive = TRUE)

if (!file.exists(src)) stop("Missing ", src, " - run 03_jobs_join.R first.")

full <- fromJSON(src, simplifyVector = FALSE)

# a1/a2/windows/dropped added 2026-07-31 for Job Displacement sections 03 and
# 04 (employment by adoption tercile; JOLTS flows by tercile). `windows` carries
# the BTOS question-change date and `dropped` the count of sectors with no CES
# match, both of which the section notes quote, so neither is written into the
# HTML by hand and neither can go stale. Measured: 54 KB -> ~160 KB.
TOP_KEEP     <- c("vintage", "ces_latest", "jolts_latest", "counts", "jolts_groups",
                  "windows", "dropped", "a1", "a2")
MONITOR_KEEP <- c("board", "decomp", "quad", "mde", "scorecard", "nat_adopt",
                  "total_private_chg")

miss <- setdiff(TOP_KEEP, names(full))
if (length(miss)) stop("btos_jobs.json is missing: ", paste(miss, collapse = ", "))
miss <- setdiff(MONITOR_KEEP, names(full$monitor))
if (length(miss)) stop("btos_jobs.json$monitor is missing: ", paste(miss, collapse = ", "))

payload <- full[TOP_KEEP]
payload$monitor <- full$monitor[MONITOR_KEEP]

js <- paste0(
  "// AUTO-GENERATED by data_analysis/btos/run_jobs.R -- do not edit by hand.\n",
  "// Regenerate: Rscript data_analysis/btos/{03_jobs_join,run_jobs}.R\n",
  "window.BTOS_JOBS_MONITOR = ",
  toJSON(payload, auto_unbox = TRUE, pretty = TRUE, digits = 5, null = "null"),
  ";\n"
)

target <- file.path(data_dir, "btos-jobs-monitor-data.js")
# UTF-8 explicitly: plain writeLines() uses the session's native encoding, which
# on a non-UTF-8 locale corrupts multibyte characters.
con <- file(target, open = "w", encoding = "UTF-8")
writeLines(enc2utf8(js), con, useBytes = TRUE)
close(con)
cat(sprintf("Wrote %s (%s bytes)\n", target,
            format(file.info(target)$size, big.mark = ",")))
